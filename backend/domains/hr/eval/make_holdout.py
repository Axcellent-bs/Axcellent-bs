TYPE = {"P": "paraphrase", "L": "long_mixed", "N": "no_answer_adjacent", "U": "no_answer_unrelated"}


def main() -> None:
    cards = json.loads((HERE / "cards.json").read_text(encoding="utf-8"))
    func_of = {c["card_id"]: c["extra"]["function"] for c in cards}
    out, count = [], {}
    for fn, typ, query, nums in Q:
        for n in nums:
            cid = f"gold_{n}"
            assert func_of[cid] == FUNC[fn], (query, cid)
        assert (typ in "NU") == (not nums), query
        count[(fn, typ)] = count.get((fn, typ), 0) + 1
        out.append(
            {
                "query_id": f"h_{fn}{typ}{count[(fn, typ)]:02d}",
                "function": FUNC[fn],
                "type": TYPE[typ],
                "query": query,
                "expected": [f"gold_{n}" for n in nums],
                "pool": FUNC[fn],
                "split": "holdout",
            }
        )
    assert len({q["query"] for q in out}) == len(out)
    (HERE / "queries_holdout.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    answerable = sum(1 for q in out if q["expected"])
    print(f"검증용 질의 {len(out)}개 (정답 있음 {answerable}, 없음 {len(out) - answerable})")


if __name__ == "__main__":
    main()

